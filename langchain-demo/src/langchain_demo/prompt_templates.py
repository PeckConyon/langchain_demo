from dotenv import load_dotenv
from langchain.chat_models import init_chat_model
from langchain_core.prompts import (
    AIMessagePromptTemplate,
    ChatPromptTemplate,
    HumanMessagePromptTemplate,
    SystemMessagePromptTemplate,
)


def build_example_prompt() -> ChatPromptTemplate:
    # Use case: demonstrate the answer format before asking a new question.
    # This is one-shot prompting: one example question plus one example answer.
    return ChatPromptTemplate.from_messages([
        SystemMessagePromptTemplate.from_template(
            "You are a Python tutor teaching a {level} student. "
            "Follow the example answer's Definition / Example / Try it structure."
        ),
        HumanMessagePromptTemplate.from_template("Explain {example_topic}."),
        # This is an assistant reply WE supply, not text generated by the model.
        # Formatting creates an AIMessage and places it in the prompt as an example.
        # Tuple shorthand for the same template: ("ai", "{example_answer}").
        AIMessagePromptTemplate.from_template("{example_answer}"),
        # End with the real question so the model answers this topic next.
        HumanMessagePromptTemplate.from_template("Explain {topic}."),
    ])

def run() -> None:
    # Load settings from .env, including OPENAI_API_KEY, into the environment.
    load_dotenv()

    # Configure the model; no API request is made until llm.invoke() below.
    # LangChain infers OpenAI as the provider from this model name.
    llm = init_chat_model(
        model="gpt-4.1-mini",
        # Low temperature reduces randomness; it does not guarantee accuracy.
        temperature=0.1,
    )

    # Style 1: tuple shorthand. Each tuple contains (message role, template text).
    # from_messages() converts "system" and "human" tuples into the corresponding
    # message prompt templates. {level} and {topic} remain placeholders for now.
    # The two adjacent system strings are joined automatically by Python.
    # This template is shown for comparison; the code below uses prompt_template.
    prompt = ChatPromptTemplate.from_messages([
        (
            "system",
            "You are a Python tutor teaching a {level} student. "
            "Keep your explanation short and include one code example.",
        ),
        (
            "human",
            "Explain {topic}."
        ),
    ])
    # Style 2: explicitly construct each message prompt template.
    # SystemMessagePromptTemplate.from_template(text) corresponds to ("system", text),
    # and HumanMessagePromptTemplate.from_template(text) to ("human", text).
    # Both styles are current and produce equivalent templates with identical text;
    # tuple shorthand is more concise, while explicit objects can be reused separately.
    # These examples have different text: only Style 1 requests a short explanation
    # and a code example. That instruction is NOT included in the model call below.
    # The system message sets the tutor's role; the human message asks a question.
    prompt_template = ChatPromptTemplate.from_messages([
        SystemMessagePromptTemplate.from_template("You are a Python tutor teaching a {level} student."),
        HumanMessagePromptTemplate.from_template("Explain {topic}.")
    ])

    # Option 1: format_messages() takes keyword arguments and returns a list
    # of message objects. It only formats text; it does not call the model.
    formatted_prompt = prompt_template.format_messages(
        level="beginner",
        topic="LangChain"
    )

    # Option 2: invoke() takes a dictionary and returns a ChatPromptValue.
    # It also only formats the template. Use .to_messages() on the result
    # if you need a list of messages like the one returned by Option 1.
    # This assignment replaces the previous formatted_prompt, so the model
    # below receives the topic "list comprehensions", not "LangChain".
    formatted_prompt = prompt_template.invoke({
        "level": "beginner",
        "topic": "list comprehensions",
    })

    # Both formatting options are accepted by llm.invoke(); normally choose one.
    # This is the actual API call: send the messages and wait for an AIMessage.
    response = llm.invoke(formatted_prompt)
    # Print the answer content rather than the entire message and its metadata.
    print("Response:", response.content)

    # Extended example: show the model an assistant answer to imitate.
    example_prompt = build_example_prompt()
    example_messages = example_prompt.format_messages(
        level="beginner",
        example_topic="lists",
        example_answer=(
            "Definition: A list stores items in order.\n"
            "Example: colors = ['red', 'blue']; print(colors[0])\n"
            "Try it: Add 'green' to colors using append()."
        ),
        topic="dictionaries",
    )

    # Inspect the four roles: system -> human -> ai -> human.
    # No model call has happened for this extended example yet.
    print("\nExample prompt messages:")
    for message in example_messages:
        print(f"[{message.type}] {message.content}\n")

    # A SECOND API request generates a new answer about dictionaries.
    # The supplied AIMessage guides the format; it does not train the model
    # permanently or guarantee exact output formatting.
    example_response = llm.invoke(example_messages)
    print("Answer using the example format:", example_response.content)
